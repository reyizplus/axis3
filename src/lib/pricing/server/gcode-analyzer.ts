import * as fs from 'fs';
import * as readline from 'readline';
import type { GCodeAnalysisResult } from '../types';

export class GCodeAnalyzer {
  async analyze(gcodePath: string, materialDensity?: number): Promise<GCodeAnalysisResult> {
    try {
      const density = materialDensity || 1.24;
      const header = await this.parseHeader(gcodePath);

      // Refuse to analyse simulated output: it would produce plausible-looking
      // filament/time numbers that are not derived from the model at all.
      if (Object.values(header).some((value) => typeof value === 'string' && value.includes('SIMULATED'))) {
        return {
          success: false,
          filamentWeightGrams: 0,
          supportWeightGrams: 0,
          filamentLengthMm: 0,
          actualPrintTimeSeconds: 0,
          actualPrintTimeHours: 0,
          totalLayerCount: 0,
          minLayerHeightMm: 0,
          maxLayerHeightMm: 0,
          totalTravelDistanceMm: 0,
          totalExtrusionDistanceMm: 0,
          retractionCount: 0,
          rawHeader: header,
          error: 'Simulated G-Code cannot be analysed',
        };
      }

      const timeSeconds = this.extractTime(header);
      const filamentMm = this.extractFilamentLength(header);
      const layerCount = this.extractLayerCount(header);

      let totalTravel = 0;
      let totalExtrusion = 0;
      let retractionCount = 0;
      let minLayerHeight = 999;
      let maxLayerHeight = 0;
      let parsedLayerCount = layerCount;
      let supportExtrusion = 0;

      if (!timeSeconds || !layerCount) {
        const detailed = await this.fullParse(gcodePath);
        totalTravel = detailed.totalTravel;
        totalExtrusion = detailed.totalExtrusion;
        retractionCount = detailed.retractionCount;
        minLayerHeight = detailed.minLayerHeight;
        maxLayerHeight = detailed.maxLayerHeight;
        parsedLayerCount = detailed.layerCount;
        supportExtrusion = detailed.supportExtrusion || 0;
      }

      const finalTimeSeconds = timeSeconds || Math.round(totalExtrusion / 10);
      const finalLayerCount = parsedLayerCount || 50;

      const filamentWeightGrams = this.calculateFilamentWeight(filamentMm || totalExtrusion, density);
      const supportWeightGrams = supportExtrusion > 0
        ? this.calculateFilamentWeight(supportExtrusion, density)
        : filamentWeightGrams * 0.15;

      return {
        success: true,
        filamentWeightGrams: this.round(filamentWeightGrams, 4),
        supportWeightGrams: this.round(supportWeightGrams, 4),
        filamentLengthMm: this.round(filamentMm || totalExtrusion, 2),
        actualPrintTimeSeconds: finalTimeSeconds,
        actualPrintTimeHours: this.round(finalTimeSeconds / 3600, 2),
        totalLayerCount: finalLayerCount,
        minLayerHeightMm: this.round(minLayerHeight === 999 ? 0.2 : minLayerHeight, 4),
        maxLayerHeightMm: this.round(maxLayerHeight, 4),
        totalTravelDistanceMm: this.round(totalTravel, 2),
        totalExtrusionDistanceMm: this.round(totalExtrusion, 2),
        retractionCount,
        rawHeader: header,
        error: null,
      };
    } catch (error) {
      return {
        success: false,
        filamentWeightGrams: 0,
        supportWeightGrams: 0,
        filamentLengthMm: 0,
        actualPrintTimeSeconds: 0,
        actualPrintTimeHours: 0,
        totalLayerCount: 0,
        minLayerHeightMm: 0,
        maxLayerHeightMm: 0,
        totalTravelDistanceMm: 0,
        totalExtrusionDistanceMm: 0,
        retractionCount: 0,
        rawHeader: {},
        error: error instanceof Error ? error.message : 'G-Code analysis failed',
      };
    }
  }

  private async parseHeader(gcodePath: string): Promise<Record<string, string>> {
    const header: Record<string, string> = {};
    const stream = fs.createReadStream(gcodePath, { encoding: 'utf-8' });
    const rl = readline.createInterface({ input: stream, crlfDelay: Infinity });

    let lineCount = 0;
    for await (const line of rl) {
      if (lineCount > 100) break;
      lineCount++;

      const trimmed = line.trim();

      if (trimmed.startsWith(';TIME:')) {
        header.TIME = trimmed.replace(';TIME:', '').trim();
      } else if (trimmed.includes('SIMULATED')) {
        header.SIMULATED = 'true';
      } else if (trimmed.startsWith(';MATERIAL:')) {
        header.MATERIAL = trimmed.replace(';MATERIAL:', '').trim();
      } else if (trimmed.startsWith(';LAYER_COUNT:')) {
        header.LAYER_COUNT = trimmed.replace(';LAYER_COUNT:', '').trim();
      } else if (trimmed.toLowerCase().includes('filament used')) {
        const match = trimmed.match(/[\d.]+/);
        if (match) header.FILAMENT_USED = match[0];
      } else if (trimmed.startsWith(';Generated by')) {
        header.GENERATOR = trimmed.replace(';Generated by', '').trim();
      }

      if (!trimmed.startsWith(';') && trimmed.length > 0) {
        break;
      }
    }

    stream.close();
    return header;
  }

  private async fullParse(gcodePath: string): Promise<{
    totalTravel: number;
    totalExtrusion: number;
    retractionCount: number;
    minLayerHeight: number;
    maxLayerHeight: number;
    layerCount: number;
    supportExtrusion: number;
  }> {
    let totalTravel = 0;
    let totalExtrusion = 0;
    let retractionCount = 0;
    let minLayerHeight = 999;
    let maxLayerHeight = 0;
    let layerCount = 0;
    let currentZ = 0;
    let supportExtrusion = 0;
    let inSupport = false;

    const stream = fs.createReadStream(gcodePath, { encoding: 'utf-8' });
    const rl = readline.createInterface({ input: stream, crlfDelay: Infinity });

    for await (const line of rl) {
      const trimmed = line.trim();
      if (!trimmed || trimmed.startsWith(';')) {
        if (trimmed.startsWith(';LAYER:')) {
          layerCount++;
        }
        if (trimmed.toLowerCase().includes('support') && trimmed.includes('TYPE:')) {
          inSupport = true;
        }
        if (trimmed.includes('TYPE:') && !trimmed.toLowerCase().includes('support')) {
          inSupport = false;
        }
        continue;
      }

      const eMatch = trimmed.match(/E([\d.-]+)/);
      if (eMatch) {
        const eValue = parseFloat(eMatch[1]);
        if (eValue > 0) {
          totalExtrusion += eValue;
          if (inSupport) supportExtrusion += eValue;
        } else if (eValue < 0) {
          retractionCount++;
        }
      }

      if (trimmed.startsWith('G0') || trimmed.startsWith('G1')) {
        const xMatch = trimmed.match(/X([\d.]+)/);
        const yMatch = trimmed.match(/Y([\d.]+)/);
        if (xMatch && yMatch && !eMatch) {
          totalTravel += Math.abs(parseFloat(xMatch[1])) + Math.abs(parseFloat(yMatch[1]));
        }
      }

      const zMatch = trimmed.match(/G1\s+Z([\d.]+)/);
      if (zMatch) {
        const z = parseFloat(zMatch[1]);
        if (z > currentZ) {
          const dz = z - currentZ;
          if (dz > 0 && dz < 1) {
            minLayerHeight = Math.min(minLayerHeight, dz);
            maxLayerHeight = Math.max(maxLayerHeight, dz);
          }
          currentZ = z;
        }
      }
    }

    stream.close();
    return { totalTravel, totalExtrusion, retractionCount, minLayerHeight, maxLayerHeight, layerCount, supportExtrusion };
  }

  private extractTime(header: Record<string, string>): number | null {
    if (header.TIME) {
      const time = parseInt(header.TIME, 10);
      if (!isNaN(time) && time > 0) return time;
    }
    return null;
  }

  private extractFilamentLength(header: Record<string, string>): number | null {
    if (header.MATERIAL) {
      const material = parseFloat(header.MATERIAL);
      if (!isNaN(material) && material > 0) return material;
    }
    if (header.FILAMENT_USED) {
      const filament = parseFloat(header.FILAMENT_USED);
      if (!isNaN(filament) && filament > 0) return filament * 1000;
    }
    return null;
  }

  private extractLayerCount(header: Record<string, string>): number | null {
    if (header.LAYER_COUNT) {
      const count = parseInt(header.LAYER_COUNT, 10);
      if (!isNaN(count) && count > 0) return count;
    }
    return null;
  }

  private calculateFilamentWeight(lengthMm: number, density: number = 1.24): number {
    const filamentDiameter = 1.75;
    const radiusMm = filamentDiameter / 2;
    const volumeMm3 = Math.PI * radiusMm * radiusMm * lengthMm;
    return (volumeMm3 / 1000) * density;
  }

  private round(value: number, precision: number): number {
    const multiplier = Math.pow(10, precision);
    return Math.round(value * multiplier) / multiplier;
  }
}

export const gcodeAnalyzer = new GCodeAnalyzer();
