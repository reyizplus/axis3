import test from 'node:test';
import assert from 'node:assert/strict';

import { buildGcodePreview, encodeGcodePreview, PREVIEW_TYPES } from './gcode-preview.mjs';

/** Önizleme tür kimlikleri (testlerde okunabilirlik için). */
const T = Object.fromEntries(PREVIEW_TYPES.map((type, index) => [type.id, index]));

/**
 * Sentetik G-Code. Gerçek PrusaSlicer çıktısındaki kritik desenleri taşır:
 * - destek bloğu ile nesne bloğu aynı Z'yi paylaşır (ayrı `;LAYER_CHANGE`),
 * - mutlak (`M82`) ve göreli (`M83`) ekstrüzyon,
 * - `G92 E0` sıfırlaması,
 * - destek dışarıda (nesne sınırlarından farklı).
 */
function buildGcode({ relativeE = false } = {}) {
  let absoluteE = 0;
  const lines = [
    '; generated by PrusaSlicer 2.5.0+dfsg-4 on 2026-11-14 at 10:00:00 UTC',
    ';',
    '; filament used [mm] = 2000.00',
    '; filament used [g] = 5.00',
    '; total filament used [g] = 5.00',
    '; estimated printing time (normal mode) = 1m 40s',
    ';',
    '; prusaslicer_config = begin',
    '; layer_height = 0.2',
    '; fill_density = 20%',
    '; perimeters = 2',
    '; support_material = 1',
    '; prusaslicer_config = end',
    '',
    relativeE ? 'M83 ; relative extrusion' : 'M82 ; absolute extrusion',
    'G92 E0',
    ';LAYER_CHANGE',
    ';Z:0.2',
    ';HEIGHT:0.2',
    'G1 Z.2 F7200',
    'G1 X90 Y90 F7200',
    ';TYPE:Support material',
    extrude(92, 90, 1),
    ';LAYER_CHANGE',
    ';Z:0.2',
    ';HEIGHT:0.2',
    'G1 X10 Y10 F7200',
    ';TYPE:External perimeter',
    extrude(11, 10, 1),
    extrude(11, 12, 1),
    ';LAYER_CHANGE',
    ';Z:0.4',
    ';HEIGHT:0.2',
    'G1 Z.4 F7200',
    'G1 X10 Y11 F7200',
    ';TYPE:Solid infill',
    extrude(12, 11, 1),
    'G0 X20 Y20',
    '',
  ];

  return lines.join('\n');

  /** Ekstrüzyon hareketi; moda göre mutlak/göreli E üretir. */
  function extrude(toX, toY, amount) {
    if (relativeE) return `G1 X${toX} Y${toY} E${amount} F1800`;
    absoluteE += amount;
    return `G1 X${toX} Y${toY} E${absoluteE} F1800`;
  }
}

function decode(buffer) {
  const headerLength = buffer.readUInt32LE(0);
  const meta = JSON.parse(buffer.subarray(4, 4 + headerLength).toString('utf8'));

  const arraysStart = (4 + headerLength + 3) & ~3;
  const positionsStart = arraysStart;
  const typesStart = positionsStart + meta.segmentCount * 12;
  const layersStart = (typesStart + meta.segmentCount + 3) & ~3;
  const speedsStart = layersStart + meta.segmentCount * meta.layerIndexBytes;

  const positions = new Int16Array(meta.segmentCount * 6);
  for (let i = 0; i < positions.length; i += 1) {
    positions[i] = buffer.readInt16LE(positionsStart + i * 2);
  }

  const types = new Uint8Array(meta.segmentCount);
  for (let i = 0; i < types.length; i += 1) {
    types[i] = buffer[typesStart + i];
  }

  const readLayer =
    meta.layerIndexBytes === 2
      ? (offset) => buffer.readUInt16LE(offset)
      : (offset) => buffer.readUInt32LE(offset);

  const layers = new Uint16Array(meta.segmentCount);
  for (let i = 0; i < layers.length; i += 1) {
    layers[i] = readLayer(layersStart + i * meta.layerIndexBytes);
  }

  const speeds = new Uint16Array(meta.segmentCount);
  for (let i = 0; i < speeds.length; i += 1) {
    speeds[i] = buffer.readUInt16LE(speedsStart + i * 2);
  }

  return { meta, positions, types, layers, speeds };
}

test('aynı Z paylaşan destek ve nesne bloklarını tek katmanda birleştirir', () => {
  const preview = buildGcodePreview(buildGcode());

  assert.equal(preview.meta.layers.length, 2, '0.2 mm iki blok tek katman olmalı');
  assert.deepEqual(
    preview.meta.layers.map((layer) => layer.z),
    [0.2, 0.4]
  );
  assert.equal(preview.meta.layers[0].object, true);
  assert.equal(preview.meta.layers[0].height, 0.2);
  // Nesne katmanı sayısı: iki katmanın ikisinde de nesne bölümü var.
  assert.equal(preview.meta.stats.layerCount, 2);
});

test('destek hareketlerini ayrı türde toplar ve gramı başlığa ölçekler', () => {
  const preview = buildGcodePreview(buildGcode());

  const support = preview.meta.types[T.support];
  const outer = preview.meta.types[T.outer_wall];
  const solid = preview.meta.types[T.solid_infill];
  const travel = preview.meta.types[T.travel];

  assert.equal(support.extrusionMm, 1);
  assert.equal(outer.extrusionMm, 2);
  assert.equal(solid.extrusionMm, 1);
  assert.ok(support.grams > 0, 'destek gramı sıfırdan büyük olmalı');
  assert.ok(Math.abs(support.grams - 5 * (1 / 4)) < 0.002);

  // Toplam gram başlıktaki 5.00 g ile aynı olmalı (destek dahil).
  const totalGrams = preview.meta.types.reduce((sum, type) => sum + type.grams, 0);
  assert.ok(Math.abs(totalGrams - 5) < 0.01, `toplam gram ${totalGrams}`);

  assert.equal(travel.grams, 0);
  assert.ok(travel.travelMm > 0, 'seyahat yolu ölçülmüş olmalı');
  assert.equal(travel.visible, false);
  assert.ok(preview.meta.layers[0].supportGrams > 0);
});

test('sınırlar seyahati kapsar, nesne sınırları yalnızca ekstrüzyonu', () => {
  const preview = buildGcodePreview(buildGcode());

  // Seyahat 90/90'a gider; genel sınırlar onu içerir.
  assert.deepEqual(preview.meta.bounds.min, [10, 10, 0.2]);
  assert.deepEqual(preview.meta.bounds.max, [92, 90, 0.4]);

  // Yazdırma sınırları: destek dahil, seyahat hariç.
  assert.deepEqual(preview.meta.printBounds.min, [10, 10, 0.2]);
  assert.deepEqual(preview.meta.printBounds.max, [92, 90, 0.4]);

  // Önizleme konumları bu sınırlara normalize edilir → uçlar ±32767.
  const xs = [];
  for (let i = 0; i < preview.positions.length; i += 6) {
    xs.push(preview.positions[i], preview.positions[i + 3]);
  }
  assert.equal(Math.max(...xs), 32767);
  assert.equal(Math.min(...xs), -32767);
});

test('göreli ekstrüzyon (M83) mutlak modla aynı sonucu verir', () => {
  const absolute = buildGcodePreview(buildGcode());
  const relative = buildGcodePreview(buildGcode({ relativeE: true }));

  assert.equal(relative.segmentCount, absolute.segmentCount);
  assert.deepEqual(relative.meta.bounds, absolute.meta.bounds);

  for (const type of PREVIEW_TYPES) {
    assert.ok(
      Math.abs(relative.meta.types[T[type.id]].extrusionMm - absolute.meta.types[T[type.id]].extrusionMm) < 0.01,
      `${type.id} ekstrüzyonu eşleşmeli`
    );
  }
});

test('ikili biçim başlığı ve dizileri kayıpsız taşır', () => {
  const preview = buildGcodePreview(buildGcode());
  const buffer = encodeGcodePreview(preview);
  const decoded = decode(buffer);

  assert.equal(decoded.meta.segmentCount, preview.segmentCount);
  assert.equal(decoded.meta.version, 1);
  assert.deepEqual(decoded.meta.bounds, preview.meta.bounds);
  assert.deepEqual(decoded.meta.types.map((type) => type.id), PREVIEW_TYPES.map((type) => type.id));

  assert.equal(decoded.types.length, preview.segmentCount);
  for (let i = 0; i < preview.segmentCount; i += 1) {
    assert.equal(decoded.types[i], preview.types[i], `tür ${i}`);
    assert.equal(decoded.layers[i], preview.layers[i], `katman ${i}`);
    assert.equal(decoded.speeds[i], preview.speeds[i], `hız ${i}`);
  }

  for (let i = 0; i < preview.positions.length; i += 1) {
    assert.equal(decoded.positions[i], preview.positions[i], `konum ${i}`);
  }
});

test('segment sınırı aşılırsa kırpma raporlanır, sessizce veri atılmaz', () => {
  const preview = buildGcodePreview(buildGcode(), { maxSegments: 2 });

  assert.equal(preview.segmentCount, 2);
  assert.ok(preview.meta.droppedSegments > 0);
});

test('hareket içermeyen gövde hata verir (uydurma önizleme yok)', () => {
  const headerOnly = [
    '; filament used [g] = 5.00',
    '; estimated printing time (normal mode) = 1m 40s',
    'M82',
    'G92 E0',
    '',
  ].join('\n');

  assert.throws(() => buildGcodePreview(headerOnly), /hareket bulunamadı/);
});
